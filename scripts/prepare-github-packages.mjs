import { execFileSync } from 'node:child_process'
import { cpSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { files, version } from '../src/releases.js'

const root = fileURLToPath(new URL('..', import.meta.url))
const library = join(root, 'public/library')
const build = join(root, '.library-build')
const catalog = JSON.parse(readFileSync(join(root, 'src/figcraft-icons.json'), 'utf8'))
if (catalog.version !== version) throw new Error(`Catalog version does not match release ${version}`)
for (const file of Object.values(files)) readFileSync(join(library, file))

mkdirSync(build, { recursive: true })
const stage = mkdtempSync(join(build, 'github-packages-'))
try {
  const flutter = join(stage, 'flutter')
  mkdirSync(flutter)
  const tar = (file, destination) => execFileSync('tar', ['-xzf', join(library, file), '-C', destination])
  tar(files.flutter, flutter)
  tar(files.apple, stage)
  execFileSync('unzip', ['-q', join(library, files.maven), '-d', stage])
  const maven = join(stage, 'raut-maven')
  const android = join(maven, 'dev/roundedicons/rounded-icons-android', version, files.android)
  if (!readFileSync(android).equals(readFileSync(join(library, files.android)))) throw new Error('Published Maven AAR must match the standalone AAR')
  cpSync(maven, join(root, 'maven'), { recursive: true })
  cpSync(flutter, join(root, 'packages/flutter'), { recursive: true })
  cpSync(join(stage, 'RautIcons/Sources'), join(root, 'packages/apple/Sources'), { recursive: true })
  const manifest = readFileSync(join(stage, 'RautIcons/Package.swift'), 'utf8')
  const localManifest = readFileSync(join(root, 'packages/apple/Package.swift'), 'utf8')
  if (manifest !== localManifest) throw new Error('Swift release archive is out of sync with packages/apple/Package.swift')
  const target = 'name: "RautIcons", resources:'
  if (!manifest.includes(target)) throw new Error('Swift manifest target layout has changed')
  writeFileSync(join(root, 'Package.swift'), manifest
    .replace('\n', '\n// Generated by npm run pack:github; edit packages/apple/Package.swift instead.\n')
    .replace(target, 'name: "RautIcons", path: "packages/apple/Sources/RautIcons", resources:'))
  console.log(`Git layouts ready: Maven, Flutter, and Swift ${version}`)
} finally {
  rmSync(stage, { recursive: true, force: true })
}
